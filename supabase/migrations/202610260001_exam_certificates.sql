alter table public.exams
  add column if not exists certificate_enabled boolean not null default false,
  add column if not exists certificate_pass_percentage numeric(5,2) not null default 50
    check (certificate_pass_percentage >= 0 and certificate_pass_percentage <= 100);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null unique references public.assignments(id) on delete cascade,
  certificate_code text not null unique,
  student_name text not null,
  exam_title text not null,
  score numeric(10,2) not null,
  max_score numeric(10,2) not null,
  percentage integer not null check (percentage >= 0 and percentage <= 100),
  issued_at timestamptz not null default now()
);

create index if not exists certificates_code_idx
  on public.certificates(certificate_code);

alter table public.certificates enable row level security;
