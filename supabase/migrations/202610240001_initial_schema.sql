create or replace function public.manara_reset_sequences()
returns void language plpgsql security definer set search_path = public as $$
declare item record;
begin
  for item in
    select table_name, column_name,
           pg_get_serial_sequence(format('public.%I', table_name), column_name) as sequence_name
    from information_schema.columns
    where table_schema='public' and is_identity='YES'
  loop
    if item.sequence_name is not null then
      execute format(
        'select setval(%L, coalesce((select max(%I) from public.%I), 1), (select count(*) > 0 from public.%I))',
        item.sequence_name, item.column_name, item.table_name, item.table_name
      );
    end if;
  end loop;
end;
$$;
revoke all on function public.manara_reset_sequences() from public, anon, authenticated;
grant execute on function public.manara_reset_sequences() to service_role;

